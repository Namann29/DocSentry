from __future__ import annotations

import re
from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from typing import Any, ClassVar

from ..extraction.base import Line, PageText, Word, bbox_of


@dataclass
class FieldDTO:
    name: str
    value: str
    normalized: str = ""
    confidence: float = 0.95
    page: int = 1
    bbox: list[float] | None = None
    snippet: str = ""
    method: str = "native_pdf"


@dataclass
class ParseResult:
    doc_type: str
    fields: list[FieldDTO] = field(default_factory=list)
    data: dict[str, Any] = field(default_factory=dict)
    warnings: list[str] = field(default_factory=list)

    def add(self, name: str, value: Any, normalized: Any = None, *, words: list[Word] | None = None,
            line: Line | None = None, confidence: float = 0.95, page: int | None = None, bbox: list[float] | None = None) -> None:
        if value is None or value == "":
            return
        ws = words if words is not None else (line.words if line else [])
        pg = page or (ws[0].page if ws else 1)
        conf = min(confidence, min((w.conf for w in ws), default=confidence))
        self.fields.append(FieldDTO(name, str(value), str(normalized if normalized is not None else value),
                                    round(conf, 3), pg, bbox_of(ws) if ws else bbox,
                                    line.text[:200] if line else ""))


class DocumentParser(ABC):
    doc_type: ClassVar[str] = "abstract"

    @abstractmethod
    def parse(self, pages: list[PageText]) -> ParseResult: ...


_REGISTRY: dict[str, type[DocumentParser]] = {}


def register(cls: type[DocumentParser]) -> type[DocumentParser]:
    """Decorator: registers a parser under its doc_type."""
    _REGISTRY[cls.doc_type] = cls
    return cls


def get_parser(doc_type: str) -> DocumentParser | None:
    cls = _REGISTRY.get(doc_type)
    return cls() if cls else None


def all_lines(pages: list[PageText]) -> list[Line]:
    return [line for p in pages for line in p.lines]


def full_text(pages: list[PageText]) -> str:
    return " ".join(line.text for line in all_lines(pages))


def letterhead(lines: list[Line]) -> tuple[str, Line | None]:
    for line in lines[:8]:
        t = line.text
        if len(t) > 2 and not re.search(r"synthetic|demo document|generated by|specimen|page \d", t, re.I):
            return t, line
    return "", None


def _label_regex(labels: dict[str, list[str]]) -> tuple[re.Pattern[str], dict[str, str]]:
    phrases = sorted(((p, k) for k, ps in labels.items() for p in ps), key=lambda x: -len(x[0]))
    alt = "|".join(re.escape(p) for p, _ in phrases)
    return re.compile(rf"(?<![A-Za-z])({alt})(?![A-Za-z])\s*[:\-â€“]?\s*", re.I), {p.lower(): k for p, k in phrases}


def labeled_values(text: str, labels: dict[str, list[str]]) -> dict[str, str]:
    """'Employee Name: Rahul   Employee Code: E1023' -> {'employee_name': 'Rahul', 'employee_code': 'E1023'}"""
    rx, keymap = _label_regex(labels)
    matches = list(rx.finditer(text))
    out: dict[str, str] = {}
    for i, m in enumerate(matches):
        key = keymap[m.group(1).lower()]
        end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
        val = text[m.end():end].strip(" :-â€“|")
        if key not in out:
            out[key] = val
    return out


def scan_labels(lines: list[Line], labels: dict[str, list[str]], allow_next_line: bool = True
                ) -> dict[str, tuple[str, Line]]:
    """First occurrence of each label across lines. Empty value -> take the next line."""
    out: dict[str, tuple[str, Line]] = {}
    for i, line in enumerate(lines):
        for key, val in labeled_values(line.text, labels).items():
            if key in out:
                continue
            if not val and allow_next_line and i + 1 < len(lines):
                nxt = lines[i + 1]
                if not labeled_values(nxt.text, labels):
                    out[key] = (nxt.text.strip(), nxt)
                    continue
            if val:
                out[key] = (val, line)
    return out