"""Demo scenarios: generated synthetic documents ingested through the SAME pipeline as uploads.
Files are renamed generically so nothing can be keyed on a filename."""
import tempfile
from pathlib import Path

from fastapi import APIRouter

from .. import audit
from ..authz import authorize
from ..db import transaction
from ..deps import DB, CurrentUser
from ..errors import NotFoundError
from ..ingest import ingest_file
from ..models import Case
from ..pipeline import process_case
from ..schemas import CaseOut
from .cases import _to_out

router = APIRouter(prefix="/demo", tags=["demo"])
SCENARIOS = {1: "Consistent documents", 2: "Salary vs bank mismatch", 3: "Duplicate invoice with altered amount",
             4: "Broken running balances", 5: "Multiple conflicting fields"}


@router.get("/scenarios")
def scenarios() -> list[dict]:
    return [{"id": k, "name": v} for k, v in SCENARIOS.items()]


@router.post("/scenarios/{sid}", response_model=CaseOut, status_code=201)
def create_demo_case(sid: int, db: DB, user: CurrentUser) -> CaseOut:
    authorize(user, "case:create")
    if sid not in SCENARIOS:
        raise NotFoundError("Unknown scenario")
    from corpus.generate import build_scenario, render_scenario  # lazy: ReportLab rendering only when needed
    scn = build_scenario(sid)
    with transaction(db):
        case = Case(title=f"Demo: {SCENARIOS[sid]}", case_type="demo", owner_id=user.id,
                    description=f"Synthetic scenario {sid} generated by the corpus generator; processed through the standard pipeline.")
        db.add(case)
        db.flush()
        with tempfile.TemporaryDirectory() as tmp:
            files = render_scenario(scn, Path(tmp))
            for i, path in enumerate(files.values(), 1):
                ingest_file(db, case, f"document_{i}.pdf", path.read_bytes(), user.id)
        audit.record(db, user.id, "case.create", "case", case.id, {"case_type": "demo", "scenario": sid})
        process_case(db, case, user.id)
    return _to_out(db, case)